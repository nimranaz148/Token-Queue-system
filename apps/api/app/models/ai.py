import uuid
from datetime import UTC, date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    Date,
    DateTime,
    ForeignKey,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import BaseModel, TenantMixin, TimestampMixin


class AIRun(BaseModel):
    """Execution telemetry and cost accounting for AI inferences."""

    __tablename__ = "ai_runs"

    clinic_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("clinics.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    feature: Mapped[str] = mapped_column(String(100), nullable=False)
    requested_by: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    provider: Mapped[str] = mapped_column(String(50), nullable=False)
    model: Mapped[str] = mapped_column(String(100), nullable=False)
    tools_called: Mapped[list[Any] | None] = mapped_column(JSONB, nullable=True)
    input_tokens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    output_tokens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    cost_usd: Mapped[Decimal] = mapped_column(
        Numeric(10, 6), default=Decimal("0.000000"), nullable=False
    )
    status: Mapped[str] = mapped_column(String(50), nullable=False)  # success | error
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
    )


class AIBrief(BaseModel, TenantMixin, TimestampMixin):
    """Daily evening brief generated by AI summarizing clinic performance."""

    __tablename__ = "ai_briefs"
    __table_args__ = (UniqueConstraint("clinic_id", "date", name="uq_ai_briefs_clinic_date"),)

    date: Mapped[date] = mapped_column(Date, nullable=False, index=True)
    body_md: Mapped[str] = mapped_column(Text, nullable=False)
    anomalies: Mapped[list[Any] | None] = mapped_column(JSONB, nullable=True)
    feedback: Mapped[str | None] = mapped_column(String(50), nullable=True)


class ChatMessage(BaseModel, TenantMixin):
    """Ephemeral conversation history between patient and AI queue assistant."""

    __tablename__ = "chat_messages"

    token_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tokens.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    role: Mapped[str] = mapped_column(String(20), nullable=False)  # patient | assistant
    content: Mapped[str] = mapped_column(Text, nullable=False)
    at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
    )


class WaitPrediction(BaseModel, TenantMixin, TimestampMixin):
    """AI estimate of wait time compared against actual outcome for accuracy tracking."""

    __tablename__ = "wait_predictions"

    token_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tokens.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    predicted_minutes: Mapped[int] = mapped_column(Integer, nullable=False)
    model_version: Mapped[str] = mapped_column(String(50), nullable=False)
    actual_minutes: Mapped[int | None] = mapped_column(Integer, nullable=True)
